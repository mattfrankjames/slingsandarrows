/**
 * Bake build-time deploy configuration into a module the functions import.
 *
 * Netlify has two environment-variable systems and they do not overlap the way
 * the file suggests. Variables declared in netlify.toml — including the
 * `[context.deploy-preview.environment]` block that was supposed to run the
 * Postgres cutover — exist only while the build runs. Functions execute later,
 * in a different process, and see only what the Netlify UI/API supplies. So
 * `USE_POSTGRES = "true"` sat in netlify.toml through every preview since the
 * cutover landed and never reached a single request: `process.env.USE_POSTGRES`
 * was undefined at runtime, and every preview quietly served Blobs.
 *
 * Per-context values in the UI are a paid feature on this plan, so the free
 * lever is the one place that does see the context: the build. This runs first
 * in `npm run build`, reads the variable while it still exists, and writes it
 * into a module that the function bundler then traces and ships.
 *
 * The generated file is committed with a false default so imports resolve
 * locally and in tests, where the environment variable is the override instead.
 */

import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const OUT = fileURLToPath(new URL('../netlify/lib/build-flags.mjs', import.meta.url));

/** @param {Record<string, string|undefined>} env */
export function render(env) {
  const usePostgres = env.USE_POSTGRES === 'true';
  return `/**
 * GENERATED by scripts/write-build-flags.mjs during \`npm run build\`. Do not edit.
 *
 * Netlify's netlify.toml variables are build-time only; functions never see
 * them. This carries the build's answer into the bundle. See that script.
 */

/** Whether this deploy reads from Postgres rather than Netlify Blobs. */
export const USE_POSTGRES = ${usePostgres};
`;
}

// Importing this module must not write anything — the tests import `render`.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const contents = render(process.env);

  // Only write on a change, so a local build does not dirty the working tree.
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* first run */
  }

  if (current !== contents) writeFileSync(OUT, contents);

  console.log(
    `[build-flags] USE_POSTGRES=${process.env.USE_POSTGRES === 'true'}` +
      ` (context: ${process.env.CONTEXT ?? 'local'})`
  );
}
